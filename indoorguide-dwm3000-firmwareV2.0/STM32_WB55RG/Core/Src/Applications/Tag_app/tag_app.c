/* Function Definitions */
void tag_app_init(void)
{
	tag_init(tagID);     // Initialization of UWB configurations

/* Filter init*/
#if defined(FILTER_EKF)
	EKF_init(&ekf, At, Rt, Qt, mu_t0, sigma_t0);
#elif defined(FILTER_PF)
	PF_init(&pf, At, Rt, Qt, mu_t0);
#elif defined(FILTER_ARKF)
	ARKF_init(&arkf, At, Rt, Qt, mu_t0, sigma_t0, MODULATION_INDEX);
#else
	//
#endif /* Filter init*/
}



void tag_app(void)
{

	for (int i = 0; i < NUM_OF_ANCHORS; i++)
	{
		measurements[i] = -1;       // Setting all measurements to -1
	}

	for (uint8_t current_anchor = 1 ; current_anchor <= NUM_OF_ANCHORS ; current_anchor++)
	{
		start_ss_ranging(current_anchor,measurements);
	}
	//Todo: Add LOG_ENABLE
//	memset(buffer,0,sizeof(buffer));
//	sprintf(buffer, "AN%d: %.2f  AN%d: %.2f  AN%d: %.2f  AN%d: %.2f", 1,
//			measurements[0], 2, measurements[1], 3, measurements[2],4,measurements[3]);
//	test_run_info((unsigned char*)buffer);

#if defined(FILTER_EKF)

	EKF_predict(&ekf);                        // EKF prediction stage

	for (int i = 0; i < NUM_OF_ANCHORS; i++)  // EKF update stage
	{
		if (measurements[i] >= 0)             // Distance should be available (not -1)
		{
			Zt.distance = measurements[i];
			Zt.anchor_x = anchor_xy[i][0];
			Zt.anchor_y = anchor_xy[i][1];
			Zt.anchor_z = anchor_xy[i][2];

			EKF_update(&ekf,&Zt);
		}

	}
	current_location[0] = ekf.mubar_t[0];
	current_location[1] = ekf.mubar_t[1];

	memset(buffer,0,sizeof(buffer));
	sprintf(buffer,"Current Location-EKF : %.2f X , %.2f Y , %.2f Z",
					  ekf.mubar_t[0],ekf.mubar_t[1],ekf.mubar_t[2]);
	test_run_info((unsigned char*)buffer);

#elif defined(FILTER_PF)


	PF_predict(&pf);
	PF_update(&pf,measurements,anchor_xy,NUM_OF_ANCHORS);

	// Resample if Neff is below the threshold
	if (pf.Neff < RESAMPLING_THRESHOLD * NUM_PARTICLES)
	{
	    PF_resample(&pf);
	}


	PF_getEstimate(&pf,&current_location[0],&current_location[1]);    //Todo: Add estimate to pf struct

	memset(buffer,0,sizeof(buffer));
	sprintf(buffer,"Current Location-PF : %.2f X , %.2f Y",
									current_location[0],current_location[1]);
	test_run_info((unsigned char*)buffer);

#elif defined(FILTER_ARKF)

	ARKF_predict(&arkf);                      // ARKF prediction stage

	for (int i = 0; i < NUM_OF_ANCHORS; i++)  // ARKF update stage
	{
		if (measurements[i] >= 0)             // Distance should be available (not -1)
		{
			Zt.distance = measurements[i] - 0.4;
			Zt.anchor_x = anchor_xy[i][0];
			Zt.anchor_y = anchor_xy[i][1];
			Zt.anchor_z = anchor_xy[i][2];

			ARKF_update(&arkf,&Zt);
		}

	}
	current_location[0] = arkf.mubar_t[0];
	current_location[1] = arkf.mubar_t[1];

	memset(buffer,0,sizeof(buffer));
	sprintf(buffer,"Current Location-ARKF : %.2f X , %.2f Y , %.2f Z",
					  arkf.mubar_t[0],arkf.mubar_t[1],arkf.mubar_t[2]);
	test_run_info((unsigned char*)buffer);

#elif defined(FILTER_MULTILATERATION)

	multilateration(anchor_xy,measurements,4,multilateration_xy);

	if (!isnan(multilateration_xy[0]))
	{
		current_location[0] = multilateration_xy[0];
		current_location[1] = multilateration_xy[1];
	}

#else
//
#endif

	return;
}

